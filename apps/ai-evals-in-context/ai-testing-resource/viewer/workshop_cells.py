"""Load pre-extracted notebook cells for workshop stage display.

Reads data/workshop/notebook_cells.json (generated by scripts/extract_notebook_cells.py)
once at import time and exposes cells by stage number.
"""

import json
from pathlib import Path

_DATA_PATH = Path(__file__).resolve().parent.parent / "data" / "workshop" / "notebook_cells.json"

_CELLS = {}

if _DATA_PATH.exists():
    with open(_DATA_PATH) as f:
        _CELLS = json.load(f)


def get_stage_cells(stage_number: int) -> dict:
    """Return cells for a workshop stage as a dict keyed by cell id.

    Example: get_stage_cells(1)["rag_pipeline"]["code_html"]
    """
    stage_key = f"stage_{stage_number}"
    cells_list = _CELLS.get(stage_key, [])
    return {cell["id"]: cell for cell in cells_list}
